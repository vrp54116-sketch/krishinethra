const CROP_MAP: Map<string, Crop> = new Map(CROPS.map((c) => [c.id.toLowerCase(), c]));

export function getCrop(id: string | null | undefined): Crop | undefined {
  if (!id) return undefined;
  return CROP_MAP.get(id.toLowerCase().trim());
}

export const cropsByCat: Record<CropCategory, Crop[]> = (() => {
  const record: Record<CropCategory, Crop[]> = {
    Cereals: [],
    Pulses: [],
    Oilseeds: [],
    Vegetables: [],
    Fruits: [],
    Spices: [],
    "Tubers & Roots": [],
    "Plantation & Commercial": [],
    Fodder: [],
    Flowers: [],
    "Medicinal & Herbal": [],
  };
  for (const crop of CROPS) {
    record[crop.cat]?.push(crop);
  }
  return record;
})();

export function searchCrops(q: string, cat?: CropCategory): Crop[] {
  const query = q.toLowerCase().trim();
  return CROPS.filter((c) => {
    if (cat && c.cat !== cat) return false;
    if (!query) return true;
    return (
      c.en.toLowerCase().includes(query) ||
      c.hi.toLowerCase().includes(query) ||
      c.id.toLowerCase().includes(query)
    );
  });
}
