export type CropCategory =
  | "Cereals"
  | "Pulses"
  | "Oilseeds"
  | "Vegetables"
  | "Fruits"
  | "Spices"
  | "Tubers & Roots"
  | "Plantation & Commercial"
  | "Fodder"
  | "Flowers"
  | "Medicinal & Herbal";

export type CropSeason = "kharif" | "rabi" | "zaid" | "perennial";

export type CropWater = "low" | "med" | "high";

export interface CropStage {
  name: string;
  from: number; // day offset (e.g. 0)
  to: number;   // day offset (e.g. 25)
  tasks: string[];
}

export interface Crop {
  id: string;
  en: string;
  hi: string;
  cat: CropCategory;
  season: CropSeason;
  days: number;
  water: CropWater;
  ph: [number, number];
  temp: [number, number];
  companions: string[];
  avoid: string[];
  rotateNext: string[];
  stages: CropStage[];
}

